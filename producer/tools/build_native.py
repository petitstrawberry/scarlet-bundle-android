#!/usr/bin/env python3
"""Build and package the native Android manager/runtime release overlay."""
from __future__ import annotations

import argparse
import gzip
import json
import os
from pathlib import Path, PurePosixPath
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[2]
TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import build_session
import native_archive
import publish_release
from native_archive import NativeArchiveError

TARGET = "aarch64-unknown-scarlet"
VERSION = publish_release.VERSION_PATTERN


class NativeBuildError(ValueError):
    """A native input or output cannot be used for a release."""


def _run(command: list[str], *, cwd: Path, env: dict[str, str] | None = None) -> None:
    subprocess.run(command, cwd=cwd, env=env, check=True)


def build_runtime(directory: Path) -> Path:
    target = directory / "target"
    _run([
        "cargo", "build", "--locked", "--release", "--target", TARGET,
    ], cwd=ROOT / "runtime", env={**os.environ, "CARGO_TARGET_DIR": str(target)})
    binary = target / TARGET / "release" / "android-runtime"
    build_session.validate_runtime(binary)
    return binary


def build_app(directory: Path) -> Path:
    app = directory / "android.app"
    _run([
        "cargo-scarlet", "app", "build",
        "--source", str(ROOT / "manager/app.toml"),
        "--target", TARGET,
        "--release",
        "--output", str(app),
    ], cwd=ROOT)
    build_session.validate_android_app(app)
    return app


def write_archive(app: Path, runtime: Path, manager_fs: Path, output: Path) -> str:
    app_tree = build_session.validate_android_app(app)
    runtime_file = build_session.validate_runtime(runtime)
    manager_tree = build_session.validate_manager_fs(manager_fs)

    entries: dict[str, build_session.HostFile] = {}
    for path, item in app_tree.files.items():
        if path in entries:
            raise NativeBuildError(f"duplicate native target: {path}")
        entries[path] = item
    for path, item in manager_tree.files.items():
        if path in entries:
            raise NativeBuildError(f"duplicate native target: {path}")
        entries[path] = item
    if native_archive.MANAGER in entries:
        raise NativeBuildError(f"manager filesystem conflicts with {native_archive.MANAGER}")
    entries[native_archive.MANAGER] = runtime_file

    directories = {native_archive.NATIVE_ROOT}
    for path in entries:
        parent = PurePosixPath(path).parent
        while str(parent) != ".":
            directories.add(f"{native_archive.NATIVE_ROOT}/{parent}")
            parent = parent.parent

    with output.open("xb") as raw, \
            gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed, \
            tarfile.open(fileobj=compressed, mode="w|", format=tarfile.PAX_FORMAT) as archive:
        for directory in sorted(directories, key=lambda value: (value.count("/"), value)):
            archive.addfile(build_session.new_directory(directory))
        for path, item in sorted(entries.items()):
            target = f"{native_archive.NATIVE_ROOT}/{path}"
            build_session.write_file(
                archive, build_session.overlay_file_info(target, item, None),
                item.source, item.sha256)
    return native_archive.validate_native_archive(output)["sha256"]


def update_release_documents(output: Path, version: str, aosp_name: str,
                             native_name: str) -> None:
    aosp = output / aosp_name
    native = output / native_name
    if not aosp.is_file() or not native.is_file():
        raise NativeBuildError("both release archives must exist before writing the manifest")
    aosp_digest = native_archive.sha256_file(aosp)
    native_digest = native_archive.validate_native_archive(native)["sha256"]
    (output / "SHA256SUMS").write_text(
        f"{aosp_digest}  {aosp_name}\n{native_digest}  {native_name}\n")
    manifest = publish_release.expected_manifest(
        version, aosp_name, aosp_digest, native_name, native_digest)
    lines = ["# Generated by scarlet-bundle-android.\n"]
    for layer in manifest["layers"]:
        lines.extend([
            "\n[[layers]]\n",
            "kind = \"archive\"\n",
            f"url = {json.dumps(layer['url'])}\n",
            f"sha256 = {{ aarch64 = \"{layer['sha256']['aarch64']}\" }}\n",
            f"format = \"{layer['format']}\"\n",
            f"strip_components = {layer['strip_components']}\n",
            f"to = \"{layer['to']}\"\n",
        ])
    (output / "bundle.toml").write_text("".join(lines))


def build_native(version: str, output: Path) -> Path:
    if VERSION.fullmatch(version) is None:
        raise NativeBuildError("--version must look like v0.1.0")
    output.mkdir(parents=True, exist_ok=True)
    aosp_name = f"android-aarch64-{version}.tar.gz"
    native_name = f"android-native-aarch64-{version}.tar.gz"
    native_path = output / native_name
    if native_path.exists() or native_path.is_symlink():
        raise NativeBuildError(f"refusing to overwrite {native_path.name}")
    if not (output / aosp_name).is_file():
        raise NativeBuildError(f"missing AOSP archive: {aosp_name}")

    with tempfile.TemporaryDirectory(prefix=".native-build-", dir=output) as temporary:
        directory = Path(temporary)
        app = build_app(directory)
        runtime = build_runtime(directory)
        candidate = directory / native_name
        write_archive(app, runtime, ROOT / "manager/fs", candidate)
        try:
            os.link(candidate, native_path)
        except FileExistsError as error:
            raise NativeBuildError(f"refusing to overwrite {native_path.name}") from error
    update_release_documents(output, version, aosp_name, native_name)
    print(native_path)
    return native_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "producer/artifacts")
    args = parser.parse_args()
    try:
        build_native(args.version, args.output.resolve())
    except (NativeBuildError, NativeArchiveError, build_session.InputError,
            subprocess.CalledProcessError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
